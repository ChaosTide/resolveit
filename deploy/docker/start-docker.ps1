# Starts the local Docker stack (ResolveIT web container + SQL Server 2022 container).
# First run: creates deploy\docker\.env with random passwords and writes the admin sign-in to
# deploy\docker\DOCKER_LOGIN.txt (both ignored by git). Later runs reuse them.
#   powershell -ExecutionPolicy Bypass -File deploy\docker\start-docker.ps1          # start
#   powershell -ExecutionPolicy Bypass -File deploy\docker\start-docker.ps1 -Stop    # stop (data is kept)
param([switch]$Stop)
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$compose = Join-Path $here 'docker-compose.yml'
$envFile = Join-Path $here '.env'

if ($Stop) { $ErrorActionPreference = 'Continue'; docker compose -f $compose down; exit $LASTEXITCODE }

function New-Secret([int]$length) {
    # Letters and digits plus a fixed symbol set; SQL Server requires upper, lower, digit, and symbol.
    $chars = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789'
    $bytes = [byte[]]::new($length)
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] }) + 'Aa9#'
}

if (-not (Test-Path $envFile)) {
    $admin = New-Secret 14
    @(
        "SA_PASSWORD=$(New-Secret 20)"
        "APP_DB_PASSWORD=$(New-Secret 20)"
        'ADMIN_EMAIL=admin@resolveit.local'
        "ADMIN_PASSWORD=$admin"
    ) | Set-Content -Path $envFile -Encoding ascii
    @(
        'ResolveIT Docker stack - administrator sign-in'
        'URL:      http://127.0.0.1:8081'
        'Email:    admin@resolveit.local'
        "Password: $admin"
        ''
        'Generated by deploy\docker\start-docker.ps1. Keep private; delete once you have it saved elsewhere.'
    ) | Set-Content -Path (Join-Path $here 'DOCKER_LOGIN.txt') -Encoding ascii
    Write-Output 'Created deploy\docker\.env and deploy\docker\DOCKER_LOGIN.txt'
}

# Docker prints progress on stderr; judge success by the exit code, not by stderr output.
$ErrorActionPreference = 'Continue'
docker compose -f $compose up -d --build
if ($LASTEXITCODE -ne 0) { Write-Output "docker compose failed (exit $LASTEXITCODE)"; exit $LASTEXITCODE }
Write-Output 'Waiting for the site to answer at http://127.0.0.1:8081 ...'
for ($i = 0; $i -lt 90; $i++) {
    try { $r = Invoke-WebRequest 'http://127.0.0.1:8081/login.php' -UseBasicParsing -TimeoutSec 5; if ($r.StatusCode -eq 200) { Write-Output 'ResolveIT (Docker) is running at http://127.0.0.1:8081'; exit 0 } } catch {}
    Start-Sleep -Seconds 2
}
Write-Output 'The site did not answer yet. Check: docker compose -f deploy\docker\docker-compose.yml logs web'
exit 1
